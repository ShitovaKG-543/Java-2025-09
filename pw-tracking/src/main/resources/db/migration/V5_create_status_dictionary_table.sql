-- =====================================================
-- СПРАВОЧНИК СТАТУСОВ (status_dictionary)
-- =====================================================
CREATE TABLE IF NOT EXISTS status_dictionary (
    status_code VARCHAR(20) PRIMARY KEY,              -- Код статуса (например, "5")
    status_name VARCHAR(200) NOT NULL,                -- Название статуса (например, "Вручение адресату")
    status_description TEXT,                          -- Описание статуса
    service_name VARCHAR(50),                         -- Для какой службы (NULL - общий)
    emoji VARCHAR(10),                                -- Эмодзи для статуса (можно хранить тут)
    sort_order INTEGER DEFAULT 0                      -- Порядок сортировки
);

